create table if not exists public.call_participants (id bigint generated by default as identity primary key, call_id bigint not null references public.active_calls(id) on delete cascade, user_id text not null, username text not null, joined_at timestamptz not null default now()); create index if not exists call_participants_call_id_idx on public.call_participants (call_id); alter table public.call_participants enable row level security; drop policy if exists "call_participants_select" on public.call_participants; drop policy if exists "call_participants_insert" on public.call_participants; drop policy if exists "call_participants_update" on public.call_participants; drop policy if exists "call_participants_delete" on public.call_participants; create policy "call_participants_select" on public.call_participants for select to anon, authenticated using (true); create policy "call_participants_insert" on public.call_participants for insert to anon, authenticated with check (true); create policy "call_participants_update" on public.call_participants for update to anon, authenticated using (true) with check (true); create policy "call_participants_delete" on public.call_participants for delete to anon, authenticated using (true); do $$ begin if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'call_participants') then alter publication supabase_realtime add table public.call_participants; end if; end $$;

