function getData() {
    const localData = localStorage.getItem("phantom_clan_data");
    if (!localData) {
        localStorage.setItem("phantom_clan_data", JSON.stringify(DEFAULT_CLAN_DATA));
        return DEFAULT_CLAN_DATA;
    }

    const parsed = JSON.parse(localData);
    
    // دمج البيانات لضمان عدم ضياع القوانين والرومات واللينكات والمواعيد عند التحديث
    return {
        ...parsed,
        rules: DEFAULT_CLAN_DATA.rules,
        rooms: parsed.rooms || DEFAULT_CLAN_DATA.rooms, // استخدام الرومات المخزنة أو الافتراضية
        links: DEFAULT_CLAN_DATA.links,
        schedule: DEFAULT_CLAN_DATA.schedule,
        founders: DEFAULT_CLAN_DATA.founders
    };
}
